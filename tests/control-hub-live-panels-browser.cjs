'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright-core');
const {fixture}=require('./fixtures/mission-fixture.cjs'),ControlServer=require('../src/control-server'),obs=require('../src/live-observatory');
const out=process.env.AIRODROM_UX_CAPTURE_DIR;

test('Live Logs: real poll/SSE refresh, stable disclosure/focus, truthful events, follow tail and responsive keyboard UI',async t=>{
 const f=await fixture(t),b=f.bridge;
 const m=f.create({objective:'Live Logs synthetic fixture'});
 b.controlStore.db.prepare("UPDATE cp_missions SET state='running' WHERE id=?").run(m.id);
 for(let n=0;n<45;n++)obs.record(b,{eventType:'fs.file_modified',missionId:m.id,metadata:{path:'fixture.txt',writer_class:'SAVED_FILE_CHANGE'}});
 const server=new ControlServer(b,{port:0});await server.start();t.after(()=>server.close());
 const browser=await chromium.launch({channel:'chrome',headless:true});t.after(()=>browser.close());
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 await page.addInitScript(token=>sessionStorage.setItem('airodromToken',token),server.token);
 const errors=[],writes=[];let polls=0,streams=0;
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.method()==='POST')writes.push(new URL(r.url()).pathname);if(r.url().includes('/api/product/overview'))polls++;if(r.url().includes('/api/product/live-stream'))streams++;});
 await page.goto(server.origin+'/?mission='+m.id);
 const stages=page.locator('details').filter({has:page.getByText('Execution stages',{exact:true})});
 await stages.locator('summary').click();
 await page.evaluate(()=>{window.savedDisclosure=document.querySelector('[data-panel-key$=":stages"]');window.savedDisclosure.firstElementChild.focus();window.renders=0;new MutationObserver(()=>window.renders++).observe(document.getElementById('content'),{childList:true});});
 const pollsBefore=polls;
 for(let n=0;n<12;n++){
  const before=await page.evaluate(()=>window.renders);
  obs.record(b,{eventType:'worker.tool_requested',missionId:m.id,metadata:{tool:'read'}});
  await page.waitForFunction(n=>window.renders>n,before);
  assert.equal(await stages.evaluate(el=>el.open),true);
  assert.equal(await stages.evaluate(el=>el===window.savedDisclosure),true);
  assert.equal(await page.evaluate(()=>document.activeElement===window.savedDisclosure.firstElementChild),true);
  await page.waitForTimeout(260);
 }
 await page.waitForFunction(()=>window.renders>=12);
 assert.ok(polls>pollsBefore,'background polling also ran');
 await page.getByRole('tab',{name:'Audit',exact:true}).click();
 const technical=page.locator('details').filter({has:page.getByText('Technical diagnostics',{exact:true})});
 await technical.locator('summary').click();
 await page.getByRole('tab',{name:'Outcome',exact:true}).click();
 assert.equal(await stages.evaluate(el=>el.open),true,'tab navigation retains disclosure');
 await page.getByRole('tab',{name:'Audit',exact:true}).click();
 assert.equal(await technical.evaluate(el=>el.open),true);
 await page.getByRole('button',{name:'View Live Logs',exact:true}).click();
 await page.getByText('No actively executing worker confirmed for this Mission.',{exact:true}).waitFor();
 assert.equal(await page.locator('.obs-top .chip').innerText(),'Recorded: Running');
 assert.equal(await page.getByRole('button',{name:'Run Mission',exact:true}).count(),0,'historical running state grants no Run action');
 const find=page.getByRole('searchbox',{name:'Filter observed events'}),category=page.getByLabel('Event category',{exact:true});
 await find.fill('FIXTURE.txt');await category.selectOption('File');await find.focus();
 obs.record(b,{eventType:'fs.file_modified',missionId:m.id,metadata:{path:'fixture.txt'}});
 await page.waitForTimeout(1000);
 assert.equal(await find.inputValue(),'FIXTURE.txt');assert.equal(await category.inputValue(),'File');assert.equal(await find.evaluate(el=>el===document.activeElement),true);
 const logs=page.getByRole('region',{name:'Recorded host events'});
 assert.ok(await logs.locator('[data-event-id]').count()>20);
 await logs.evaluate(el=>{el.scrollTop=el.scrollHeight;});
 await page.getByRole('button',{name:'Follow tail: On',exact:true}).waitFor();
 await logs.evaluate(el=>{el.scrollTop=140;});
 await page.getByRole('button',{name:'Follow tail: Off',exact:true}).waitFor();
 const scroll=await logs.evaluate(el=>el.scrollTop);
 obs.record(b,{eventType:'fs.file_modified',missionId:m.id,metadata:{path:'fixture.txt'}});
 await page.waitForTimeout(1000);
 assert.ok(Math.abs(await logs.evaluate(el=>el.scrollTop)-scroll)<3,'new events preserve scroll when following is off');
 assert.equal(await page.getByRole('button',{name:'Pause updates',exact:true}).count(),1,'scrolling never pauses data');
 await page.getByRole('button',{name:'Follow tail: Off',exact:true}).focus();await page.keyboard.press('Enter');
 assert.equal(await page.getByRole('button',{name:'Follow tail: On',exact:true}).getAttribute('aria-pressed'),'true');
 if(out){fs.mkdirSync(out,{recursive:true});await page.screenshot({path:path.join(out,'live-logs-desktop.png'),fullPage:true});}
 await page.getByRole('button',{name:'Pause updates',exact:true}).click();
 await page.getByRole('tab',{name:'Outcome',exact:true}).click();
 assert.equal(await stages.evaluate(el=>el.open),true);
 await page.getByRole('button',{name:'Resume updates',exact:true}).click();
 await page.waitForTimeout(1000);assert.equal(await stages.evaluate(el=>el.open),true);
 // Finite event stream exercises EOF/reconnect without touching the live service.
 await page.route('**/api/product/live-stream?*',r=>r.fulfill({status:200,contentType:'text/event-stream',body:'event: ready\ndata: {"cursor":0}\n\n'}));
 await page.getByRole('button',{name:'Pause updates',exact:true}).click();
 await page.getByRole('button',{name:'Resume updates',exact:true}).click();
 await page.getByRole('button',{name:'View Live Logs',exact:true}).click();
 const streamsBefore=streams;
 await page.waitForTimeout(6000);assert.ok(streams>streamsBefore,'EOF reconnects on polling');
 await page.unroute('**/api/product/live-stream?*');
 await page.waitForTimeout(3000);
 await page.getByRole('button',{name:'Live Activity & Logs',exact:true}).click();
 await page.getByRole('button',{name:'View Mission',exact:true}).first().waitFor();
 const timeline=page.locator('details').filter({has:page.getByText('Workflow timeline',{exact:true})}).first();
 await timeline.locator('summary').click();
 obs.record(b,{eventType:'worker.tool_requested',missionId:m.id,metadata:{tool:'read'}});
 await page.waitForTimeout(3000);assert.equal(await timeline.evaluate(el=>el.open),true);
 await page.getByRole('button',{name:'View Live Logs',exact:true}).first().click();
 await page.getByRole('heading',{name:'Live Logs',exact:true}).waitFor();
 await page.getByLabel('Appearance').selectOption('light');await page.setViewportSize({width:320,height:780});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'320px layout has no horizontal overflow');
 await page.getByRole('searchbox',{name:'Filter observed events'}).scrollIntoViewIfNeeded();await page.waitForTimeout(350);
 if(out)await page.screenshot({path:path.join(out,'live-logs-mobile.png')});
 assert.deepEqual(errors,[]);assert.deepEqual(writes,[]);assert.equal(f.inference(),0);
});

'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {fixture}=require('./fixtures/mission-fixture.cjs'),ControlServer=require('../src/control-server');
const {chromium}=require('playwright-core');
test('Mission cleanup UI: actionable Active, exact cleanup, searchable archive, restore and responsive history',async t=>{
 const f=await fixture(t),b=f.bridge,server=new ControlServer(b,{port:0});await server.start();t.after(()=>server.close());
 const draft=f.create({objective:'Draft waiting for scope'}),review=f.create({objective:'Review Acceptance fixture'}),done=f.create({objective:'Searchable settled fixture'}),cancelled=f.create({objective:'Cancelled fixture'});
 const db=b.controlStore.db;
 for(const [m,state] of [[draft,'draft'],[review,'awaiting_acceptance'],[done,'completed'],[cancelled,'cancelled']])db.prepare('UPDATE cp_missions SET state=? WHERE id=?').run(state,m.id);
 db.prepare("INSERT INTO cp_mission_settlements VALUES(?,NULL,'settled','Synthetic fixture',?)").run(done.id,Date.now());
 db.prepare("UPDATE cp_effect_outbox SET status='sent'").run();
 const browser=await chromium.launch({channel:'chrome',headless:true});t.after(()=>browser.close());
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],dialogs=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('dialog',async d=>{dialogs.push(d.message());await d.accept();});
 await page.addInitScript(token=>sessionStorage.setItem('airodromToken',token),server.token);
 await page.goto(server.origin+'/?view=Missions');
 await page.getByRole('button',{name:'Draft waiting for scope',exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Searchable settled fixture',exact:true}).count(),0);
 await page.getByRole('tab',{name:/^History/}).click();
 await page.getByRole('button',{name:'Searchable settled fixture',exact:true}).waitFor();
 await page.getByRole('button',{name:'Clean up history…',exact:true}).click();
 await page.getByText('Archived 2 Missions. All records remain searchable in History.',{exact:true}).waitFor();
 assert.match(dialogs[0],/Archive 2 of 2 eligible/);assert.doesNotMatch(dialogs[0],/Draft waiting|Review Acceptance fixture/);
 await page.getByRole('searchbox',{name:'Search Missions'}).fill('Searchable settled');
 await page.getByRole('status').filter({hasText:/1 matching/}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Restore',exact:true}).count(),1);
 await page.getByRole('button',{name:'Restore',exact:true}).click();
 await page.getByRole('button',{name:'Archive',exact:true}).waitFor();
 assert.equal(b.missions.require(done.id).state,'completed');
 await page.getByRole('button',{name:'Searchable settled fixture',exact:true}).click();
 await page.getByRole('button',{name:'← Back to Missions',exact:true}).waitFor();
 await page.getByRole('button',{name:'← Back to Missions',exact:true}).click();
 assert.equal(await page.getByRole('searchbox',{name:'Search Missions'}).inputValue(),'Searchable settled');
 await page.getByRole('status').filter({hasText:/1 matching/}).waitFor();
 await page.getByLabel('Appearance').selectOption('dark');
 const captures=process.env.AIRODROM_UX_CAPTURE_DIR;
 if(captures){fs.mkdirSync(captures,{recursive:true});await page.screenshot({path:path.join(captures,'mission-history-desktop.png'),fullPage:true});}
 await page.getByLabel('Appearance').selectOption('light');
 await page.setViewportSize({width:375,height:812});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
 if(captures)await page.screenshot({path:path.join(captures,'mission-history-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
});
